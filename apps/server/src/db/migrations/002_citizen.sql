-- 002_citizen: citizen role — ledger, energy, groups, petitions, protests, businesses, news, stories, chat, notifications.

ALTER TABLE users ADD COLUMN muted_until timestamptz;

ALTER TABLE characters
  ADD COLUMN energy numeric NOT NULL DEFAULT 100 CHECK (energy >= 0 AND energy <= 100),
  ADD COLUMN energy_updated_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN journalist_rep int NOT NULL DEFAULT 50 CHECK (journalist_rep BETWEEN 0 AND 100),
  ADD COLUMN avatar_seed text NOT NULL DEFAULT md5(random()::text);

ALTER TABLE world_state ADD COLUMN last_tick_turn int NOT NULL DEFAULT 0;

-- Every naira movement for a character. Balances live on characters; this is the history.
CREATE TABLE transactions (
  id bigserial PRIMARY KEY,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  account text NOT NULL CHECK (account IN ('wallet', 'warChest')),
  delta bigint NOT NULL CHECK (delta <> 0),
  reason text NOT NULL,
  ref_type text,
  ref_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX transactions_character_idx ON transactions(character_id, created_at DESC);

-- Real-time cooldowns for actions (rally, protest, story, ...).
CREATE TABLE action_log (
  id bigserial PRIMARY KEY,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  kind text NOT NULL,
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX action_log_character_kind_idx ON action_log(character_id, kind, at DESC);

CREATE TABLE volunteer_roles (
  id bigserial PRIMARY KEY,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  party_id uuid NOT NULL REFERENCES parties(id),
  role text NOT NULL CHECK (role IN ('ward_agent', 'delegate')),
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz
);
CREATE UNIQUE INDEX volunteer_roles_one_active ON volunteer_roles(character_id, role) WHERE ended_at IS NULL;

CREATE TABLE group_memberships (
  id bigserial PRIMARY KEY,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  group_kind text NOT NULL CHECK (group_kind IN ('labour', 'student', 'trade', 'community_watch')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  left_at timestamptz
);
CREATE UNIQUE INDEX group_memberships_one_active ON group_memberships(character_id, group_kind) WHERE left_at IS NULL;

CREATE TABLE petitions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  creator_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text NOT NULL,
  state_code text REFERENCES states(code),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE petition_signatures (
  petition_id uuid NOT NULL REFERENCES petitions(id) ON DELETE CASCADE,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  signed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (petition_id, character_id)
);

CREATE TABLE protests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organiser_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  state_code text NOT NULL REFERENCES states(code),
  issue text NOT NULL,
  title text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  ends_at timestamptz NOT NULL
);
CREATE TABLE protest_participants (
  protest_id uuid NOT NULL REFERENCES protests(id) ON DELETE CASCADE,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  outcome text NOT NULL,
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (protest_id, character_id)
);

CREATE TABLE businesses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  name text NOT NULL,
  sector text NOT NULL,
  state_code text NOT NULL REFERENCES states(code),
  capital bigint NOT NULL CHECK (capital > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz
);
CREATE INDEX businesses_owner_idx ON businesses(owner_id) WHERE closed_at IS NULL;

CREATE TABLE news_items (
  id bigserial PRIMARY KEY,
  kind text NOT NULL,
  headline text NOT NULL,
  body text NOT NULL DEFAULT '',
  state_code text REFERENCES states(code),
  actor_character_id uuid REFERENCES characters(id) ON DELETE SET NULL,
  -- 'world' = generated by the simulation, 'player' = player action, 'story' = journalist story
  source text NOT NULL CHECK (source IN ('world', 'player', 'story')),
  game_turn int,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX news_items_created_idx ON news_items(created_at DESC);

-- Journalist stories. `accurate` is computed by the server from game records and never shown to readers.
CREATE TABLE stories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  author_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  target_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  claim text NOT NULL,
  claim_param text,
  headline text NOT NULL,
  body text NOT NULL,
  accurate boolean NOT NULL,
  news_item_id bigint REFERENCES news_items(id),
  published_at timestamptz NOT NULL DEFAULT now()
);

-- ============ Chat ============
CREATE TABLE chat_groups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  owner_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE chat_group_members (
  group_id uuid NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, character_id)
);

CREATE TABLE chat_messages (
  id bigserial PRIMARY KEY,
  -- global | state:XX | party:<uuid> | dm:<uuid>:<uuid> (sorted) | group:<uuid>
  channel text NOT NULL,
  sender_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  body text NOT NULL,
  filtered boolean NOT NULL DEFAULT false,
  hidden_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX chat_messages_channel_idx ON chat_messages(channel, id DESC);

CREATE TABLE chat_blocks (
  blocker_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  blocked_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (blocker_id, blocked_id),
  CHECK (blocker_id <> blocked_id)
);

CREATE TABLE reports (
  id bigserial PRIMARY KEY,
  reporter_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  target_type text NOT NULL CHECK (target_type IN ('character', 'chat_message', 'petition', 'story')),
  target_id text NOT NULL,
  reason text NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'actioned', 'dismissed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ============ Notifications ============
CREATE TABLE notifications (
  id bigserial PRIMARY KEY,
  character_id uuid NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  kind text NOT NULL,
  title text NOT NULL,
  body text NOT NULL DEFAULT '',
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_character_idx ON notifications(character_id, id DESC);
